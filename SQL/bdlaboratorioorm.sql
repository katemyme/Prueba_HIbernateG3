--CREACION DEL ESQUEMA
CREATE SCHEMA catalogos;

--CREACION DE LA TABLA DE TIPO EQUIPO
    CREATE TABLE catalogos.tipo_equipo
    (
        id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre VARCHAR(100) NOT NULL UNIQUE,
        descripcion VARCHAR(255)
    );

--CREACION DE LA TABLA DE EQUIPOS
    CREATE TABLE catalogos.equipo
    (
        id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        codigo VARCHAR(100) NOT NULL UNIQUE,
        marca VARCHAR(100),
        nombre VARCHAR(100) NOT NULL UNIQUE,
        estado VARCHAR(100) NOT NULL,
        cantidad INTEGER NOT NULL DEFAULT 0,
        id_tipo BIGINT NOT NULL,
-- RESTRICCION PARA LA CANTIDAD
        CONSTRAINT chk_equipo_cantidad
            CHECK (cantidad>= 0),
--RESTRICCION PARA EL ESTADO DEL EQUIPO
        CONSTRAINT chk_equipo_estado
            CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),
--ESTABLECIENDO LA LLAVE FORANEA
        CONSTRAINT fk_equipo_tipo
            FOREIGN KEY(id_tipo)
                REFERENCES catalogos.tipo_equipo(id_tipo)
                ON UPDATE CASCADE
                ON DELETE RESTRICT
    );

